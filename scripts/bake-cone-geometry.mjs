#!/usr/bin/env node
// One-off dev script. Parses public/cone.glb and writes its position/uv/index
// typed arrays into src/lib/cone-geometry.ts as base64-encoded blobs. Not
// shipped — re-run by hand if the artist asset ever changes.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const glbPath = path.resolve(repoRoot, "public/cone.glb");
const outPath = path.resolve(repoRoot, "src/lib/cone-geometry.ts");

const buf = readFileSync(glbPath);
const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);

const magic = String.fromCodePoint(dv.getUint8(0), dv.getUint8(1), dv.getUint8(2), dv.getUint8(3));
if (magic !== "glTF") throw new Error(`Not a GLB: magic=${magic}`);
if (dv.getUint32(4, true) !== 2) throw new Error("Expected GLB version 2");

const jsonLength = dv.getUint32(12, true);
const jsonType = dv.getUint32(16, true);
if (jsonType !== 0x4e4f534a) throw new Error("Expected JSON chunk");
const json = JSON.parse(buf.slice(20, 20 + jsonLength).toString("utf8"));

const binHeaderOffset = 20 + jsonLength;
const binLength = dv.getUint32(binHeaderOffset, true);
const binType = dv.getUint32(binHeaderOffset + 4, true);
if (binType !== 0x004e4942) throw new Error("Expected BIN chunk");
const binStart = binHeaderOffset + 8;
const bin = buf.slice(binStart, binStart + binLength);

const primitive = json.meshes[0].primitives[0];
const positionAccessor = json.accessors[primitive.attributes.POSITION];
const uvAccessor = json.accessors[primitive.attributes.TEXCOORD_0];
const indexAccessor = json.accessors[primitive.indices];

if (positionAccessor.componentType !== 5126 || positionAccessor.type !== "VEC3") {
  throw new Error("POSITION must be float32 VEC3");
}

if (uvAccessor.componentType !== 5126 || uvAccessor.type !== "VEC2") {
  throw new Error("TEXCOORD_0 must be float32 VEC2");
}

if (indexAccessor.componentType !== 5123 || indexAccessor.type !== "SCALAR") {
  throw new Error("indices must be uint16 SCALAR");
}

const sliceView = (accessor) => {
  const view = json.bufferViews[accessor.bufferView];
  return bin.slice(view.byteOffset, view.byteOffset + view.byteLength);
};

const positionBytes = sliceView(positionAccessor);
const uvBytes = sliceView(uvAccessor);
const indexBytes = sliceView(indexAccessor);

const b64 = (bytes) => bytes.toString("base64");

const out = `// Generated by scripts/bake-cone-geometry.mjs from public/cone.glb.
// Do not edit by hand — re-run the script if the artist asset changes.

const decodeBase64 = (encoded: string): ArrayBuffer => {
  const binary = atob(encoded);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }

  return bytes.buffer;
};

export const conePositions: Float32Array = new Float32Array(
  decodeBase64(
    "${b64(positionBytes)}"
  )
);

export const coneUvs: Float32Array = new Float32Array(
  decodeBase64(
    "${b64(uvBytes)}"
  )
);

export const coneIndices: Uint16Array = new Uint16Array(
  decodeBase64(
    "${b64(indexBytes)}"
  )
);
`;

writeFileSync(outPath, out);
console.log(
  `Wrote ${outPath}: ${positionAccessor.count} positions, ${uvAccessor.count} uvs, ${indexAccessor.count} indices.`
);
